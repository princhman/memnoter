import type { JSONContent } from "@tiptap/core";
import { Fragment, type Node as ProseMirrorNode } from "@tiptap/pm/model";
import type { EditorState } from "@tiptap/pm/state";
import { diffArrays, diffLines } from "diff";
import { cardGroupsOf, parseBlock } from "./cards";
import { jsonToMarkdown } from "./markdown-export";
import { markdownToJSON, type ImageResolver } from "./markdown-paste";

type Block = { markdown: string; content: JSONContent };

export type BackupHunk = {
  from: number;
  to: number;
  before: string;
  after: string;
  blocks: JSONContent[];
  reason: string | null;
};

const protectedChange = "This change touches a card, attachment or block that Markdown cannot safely replace.";
const safeBlocks = new Set(["paragraph", "heading", "bulletList", "orderedList", "listItem", "blockquote", "codeBlock", "horizontalRule", "text", "hardBreak"]);
const safeMarks = new Set(["bold", "italic", "strike", "code", "link"]);

function canReplace(node: JSONContent): boolean {
  return safeBlocks.has(node.type ?? "") &&
    !node.attrs?.clozeNote &&
    !node.attrs?.cardGroup &&
    !node.attrs?.clozeIds?.length &&
    !node.attrs?.clozeGroups?.length &&
    !node.attrs?.pdfSource &&
    (node.marks ?? []).every(mark => safeMarks.has(mark.type) && !String(mark.attrs?.href ?? "").startsWith("attachments/")) &&
    (node.content ?? []).every(canReplace);
}

function isCardBoundary(node: JSONContent) {
  const text = (node.content ?? []).map(child => child.text ?? "").join("");
  return /(?:^::end$|\s::(?:block|list)$)/.test(text) || (node.content ?? []).some(isCardBoundary);
}

export function diffBackupNote({
  current, edited, imagePath, pdfAppendix,
}: {
  current: JSONContent;
  edited: string;
  imagePath: (id: string) => string;
  pdfAppendix: string;
}): BackupHunk[] {
  const render = (block: JSONContent) => jsonToMarkdown({ type: "doc", content: [block] }, imagePath);
  const resolveImage: ImageResolver = (src, alt) => ({ type: "image", attrs: { src, alt } });
  function parse(source: string): Block[] {
    return (markdownToJSON(source, resolveImage, { keepFrontMatter: true, resolveRemoteImages: true }).content ?? [])
      .map(content => ({ markdown: render(content), content }))
      .filter(block => block.markdown !== "");
  }

  const original = current.content ?? [];
  const before = original.flatMap((content, index) =>
    parse(render(content)).map(block => ({ ...block, index })));
  const normalized = edited.replace(/\r\n?/g, "\n").replace(/\n+$/, "");
  // PDF links are generated by the backup exporter and have no editor block.
  // Leave the appendix in the diff when someone edited it.
  const pdfSuffix = "\n\n" + pdfAppendix;
  const samePdfs = !pdfAppendix || normalized === pdfAppendix || normalized.endsWith(pdfSuffix);
  const pdfStart = pdfAppendix ? normalized.lastIndexOf("\n\n## PDFs\n") : -1;
  const note = !pdfAppendix ? normalized
    : normalized === pdfAppendix ? ""
    : samePdfs ? normalized.slice(0, -pdfSuffix.length)
    : pdfStart >= 0 ? normalized.slice(0, pdfStart)
    : normalized.startsWith("## PDFs\n") ? "" : normalized;
  const after = parse(note);
  const changes = diffArrays<Block>(before, after, {
    comparator: (a, b) => a.markdown === b.markdown,
    timeout: 500,
  });
  if (!changes) {
    return [{ from: 0, to: 0, before: "", after: "", blocks: [],
      reason: "This file has too many changes to review safely." }];
  }

  const hunks: BackupHunk[] = [];
  let left = 0;
  let right = 0;
  for (let i = 0; i < changes.length;) {
    const change = changes[i];
    if (!change.added && !change.removed) {
      left += change.count;
      right += change.count;
      i++;
      continue;
    }

    const start = left;
    const addedStart = right;
    while (i < changes.length && (changes[i].added || changes[i].removed)) {
      const part = changes[i++];
      if (part.removed) left += part.count;
      else right += part.count;
    }

    function addHunk(start: number, end: number, addedStart: number, addedEnd: number) {
      const nextIndex = before[start]?.index ?? original.length;
      const previousIndex = before[start - 1]?.index ?? -1;
      const from = nextIndex;
      const to = start === end ? from : before[end - 1].index + 1;
      const afterBlocks = after.slice(addedStart, addedEnd);
      const blocks = afterBlocks.map(block => block.content);
      const old = original.slice(from, to);
      const partialBlock = previousIndex === from || (end > start && before[end]?.index === to - 1);
      const hiddenBlock = new Set(before.slice(start, end).map(block => block.index)).size < to - from;
      hunks.push({
        from, to, blocks,
        before: before.slice(start, end).map(block => block.markdown).join("\n\n"),
        after: afterBlocks.map(block => block.markdown).join("\n\n"),
        reason: partialBlock || hiddenBlock
          || [...old, ...blocks].some(node => !canReplace(node) || isCardBoundary(node))
          || (start === end && !before[start] && original.slice(previousIndex + 1).some(node => render(node) !== ""))
          || (old.some(node => node.type === "heading") &&
            !(old.length === 1 && blocks.length === 1 && blocks[0].type === "heading" &&
              old[0].attrs?.level === blocks[0].attrs?.level))
          || (blocks.some(node => node.type === "heading") && !old.some(node => node.type === "heading"))
          ? protectedChange : null,
      });
    }
    // Adjacent one-for-one replacements can be selected independently. Keep
    // insertions/deletions together where their pairing would be ambiguous.
    if (left - start === right - addedStart && left - start > 1) {
      for (let offset = 0; offset < left - start; offset++) {
        addHunk(start + offset, start + offset + 1, addedStart + offset, addedStart + offset + 1);
      }
    } else {
      addHunk(start, left, addedStart, right);
    }
  }
  if (!samePdfs) {
    hunks.push({ from: original.length, to: original.length, before: pdfAppendix,
      after: note === normalized ? "" : normalized.slice(note ? note.length + 2 : 0),
      blocks: [], reason: "PDF links are managed in Memnoter." });
  }
  if (!hunks.length) {
    const exported = [jsonToMarkdown(current, imagePath), pdfAppendix].filter(Boolean).join("\n\n");
    if (exported !== normalized) {
      // Import can normalize markup even when the original Markdown changed.
      const lines = diffLines(exported, normalized, { timeout: 500, ignoreNewlineAtEof: true }) ?? [];
      hunks.push({ from: 0, to: 0, blocks: [],
        before: lines.filter(line => line.removed).map(line => line.value).join(""),
        after: lines.filter(line => line.added).map(line => line.value).join(""),
        reason: "The Markdown formatting changed without changing the note content." });
    }
  }
  return hunks;
}

function blockOffsets(doc: ProseMirrorNode) {
  const offsets: number[] = [];
  doc.forEach((_, pos) => offsets.push(pos));
  offsets.push(doc.content.size);
  return offsets;
}

export function protectBackupHunks(doc: ProseMirrorNode, hunks: readonly BackupHunk[]) {
  const offsets = blockOffsets(doc);
  const groups = cardGroupsOf(doc);
  function hasCard(node: ProseMirrorNode) {
    if (node.isTextblock) return parseBlock(node).cards.length > 0;
    for (let index = 0; index < node.childCount; index++) {
      if (hasCard(node.child(index))) return true;
    }
    return false;
  }
  return hunks.map(hunk => {
    if (hunk.reason) return hunk;
    const from = offsets[hunk.from];
    const to = offsets[hunk.to];
    if (from === undefined || to === undefined || groups.some(group => from < group.to && to > group.from)) {
      return { ...hunk, reason: protectedChange };
    }
    for (let index = hunk.from; index < hunk.to; index++) {
      if (hasCard(doc.child(index))) return { ...hunk, reason: protectedChange };
    }
    try {
      for (const json of hunk.blocks) {
        const node = doc.type.schema.nodeFromJSON(json);
        node.check();
        if (hasCard(node)) return { ...hunk, reason: protectedChange };
      }
    } catch {
      return { ...hunk, reason: "This Markdown uses syntax the note editor cannot apply." };
    }
    return hunk;
  });
}

export function backupChangeTransaction(state: EditorState, hunks: readonly BackupHunk[]) {
  const { doc, schema } = state;
  const offsets = blockOffsets(doc);
  const tr = state.tr;
  for (const hunk of protectBackupHunks(doc, hunks).reverse()) {
    if (hunk.reason) throw new Error(hunk.reason);
    const from = offsets[hunk.from];
    const to = offsets[hunk.to];
    const replacement = hunk.blocks.map(block => {
      const node = schema.nodeFromJSON(block);
      node.check();
      return node;
    });
    // Keep the original textblock and its references wherever possible.
    const old = doc.maybeChild(hunk.from);
    const next = replacement[0];
    if (hunk.to === hunk.from + 1 && replacement.length === 1 &&
      old?.isTextblock && next.type === old.type) {
      tr.replaceWith(from + 1, to - 1, next.content);
      if (old.attrs.language !== next.attrs.language) tr.setNodeAttribute(from, "language", next.attrs.language);
    } else {
      const content = Fragment.from(replacement);
      const start = tr.doc.resolve(from).index();
      const end = tr.doc.resolve(to).index();
      if (tr.doc.canReplace(start, end, content)) tr.replaceWith(from, to, content);
      else if (from === 0 && to === tr.doc.content.size && !replacement.length) {
        tr.replaceWith(from, to, schema.nodes.paragraph.create());
      } else {
        throw new Error("The selected blocks cannot be placed in this note.");
      }
    }
  }
  return tr;
}
