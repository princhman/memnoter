#!/usr/bin/env node
// Read declarations, rather than evaluating editor modules (which require a DOM).
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const require = createRequire(new URL('apps/shared-ui/package.json', root));
const ts = require('typescript');
const parse = path => ts.createSourceFile(path, readFileSync(new URL(path, root), 'utf8'), ts.ScriptTarget.Latest, true);
const source = parse('apps/shared-ui/src/editor-host/protocol.ts');
const interfaces = new Map(source.statements.filter(ts.isInterfaceDeclaration).map(node => [node.name.text, node]));
const constants = new Map();
for (const statement of source.statements.filter(ts.isVariableStatement)) {
  for (const declaration of statement.declarationList.declarations) {
    let value = declaration.initializer;
    if (ts.isAsExpression(value)) value = value.expression;
    constants.set(declaration.name.getText(source), value);
  }
}
const name = node => node.name.text;
const swiftName = value => value.replace(/-([a-z])/g, (_, letter) => letter.toUpperCase());
const enumFor = (type, names) => `enum ${type}: String, Codable {\n${names.map(value => `    case ${swiftName(value)} = ${JSON.stringify(value)}`).join('\n')}\n}\n`;
function swiftType(node) {
  if (ts.isUnionTypeNode(node)) {
    const nonNull = node.types.filter(t => t.getText(source) !== 'null');
    if (nonNull.length !== 1 || nonNull.length === node.types.length) throw Error(`Unsupported union: ${node.getText(source)}`);
    return swiftType(nonNull[0]) + '?';
  }
  if (ts.isArrayTypeNode(node)) return `[${swiftType(node.elementType)}]`;
  if (node.kind === ts.SyntaxKind.StringKeyword) return 'String';
  if (node.kind === ts.SyntaxKind.NumberKeyword) return 'Int';
  if (node.kind === ts.SyntaxKind.BooleanKeyword) return 'Bool';
  if (ts.isTypeReferenceNode(node) && interfaces.has(node.typeName.getText(source))) return node.typeName.getText(source);
  throw Error(`Unsupported Swift wire type: ${node.getText(source)}`);
}
let output = '// Generated by scripts/generate-bridge-protocol.mjs. Do not edit.\nimport Foundation\n\n';
output += enumFor('NativeEventName', interfaces.get('NativeEvents').members.map(name));
output += enumFor('ExecCommand', constants.get('EXEC_COMMANDS').properties.map(name));
for (const api of ['EditorApi', 'ReviewApi']) output += enumFor(api + 'Method', interfaces.get(api).members.map(name));
for (const type of ['Heading', 'SectionCrumb', 'FocusableSection', 'EditorState']) {
  output += `struct ${type}: Codable${['Heading', 'SectionCrumb'].includes(type) ? ', Identifiable' : ''} {\n`;
  for (const field of interfaces.get(type).members) {
    const fieldName = name(field), typeName = swiftType(field.type);
    const initial = typeName.endsWith('?') ? 'nil' : typeName === 'Bool' ? 'false' : typeName === 'Int' ? '0' : typeName.startsWith('[') ? '[]' : fieldName === 'blockType' ? '"paragraph"' : '""';
    output += `    var ${fieldName}: ${typeName} = ${initial}\n`;
  }
  output += '}\n';
}
output += 'enum BridgeProtocol {\n';
for (const [key, field] of Object.entries({BRIDGE_VERSION: 'version', FILE_SCHEME: 'fileScheme', APP_SCHEME: 'appScheme', EDITOR_ENTRY: 'editorEntry', REVIEW_ENTRY: 'reviewEntry'})) output += `    static let ${field} = ${constants.get(key).getText(source)}\n`;
const highlight = parse('apps/shared-ui/src/lib/highlight.ts');
const colors = highlight.statements.filter(ts.isVariableStatement).flatMap(s => [...s.declarationList.declarations]).find(d => d.name.getText(highlight) === 'HIGHLIGHT_COLORS').initializer.expression;
output += `    static let highlightColors = [${colors.elements.map(v => JSON.stringify(v.text)).join(', ')}]\n}\n`;
const target = new URL('apps/ios/Sources/Generated/BridgeProtocol.swift', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw Error('BridgeProtocol.swift is stale. Run node scripts/generate-bridge-protocol.mjs');
} else {
  mkdirSync(fileURLToPath(new URL('.', target)), { recursive: true });
  writeFileSync(target, output);
}
